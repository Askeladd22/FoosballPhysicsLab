#!/usr/bin/env python3
"""Make 'table legs BELOW the pitch' an executable invariant for real GLB.

Reads the LÖVE 28-byte interleaved position/normal/RGBA8 mesh binaries
generated by the repo's CC BY offline importer; no optional package needed.
"""
import argparse
from pathlib import Path
import struct


def bounds(path):
    raw=Path(path).read_bytes()
    assert len(raw)%28==0 and len(raw)>0, "invalid 3D mesh stream "+str(path)
    ys=[]
    # Vertex layout: vec3 position, vec3 normal, vec4 RGBA8 color.
    for pos in range(0,len(raw),28):
        ys.append(struct.unpack_from("<f",raw,pos+4)[0])
    return min(ys), max(ys),sum(y<-250 for y in ys)


def verify(folder):
    folder=Path(folder)
    table_min,table_max,below=bounds(folder/"table.bin")
    field_min,field_max,_=bounds(folder/"field.bin")
    print(("3D model orientation / Y axis: tabletop Y %.1f..%.1f, "
           "under-table supports reach Y %.1f, tall rim Y %.1f; "
           "support vertices below pitch=%d") %
          (field_min,field_max,table_min,table_max,below))
    assert -15<field_min<8 and field_max<12, (
        "source pitch is not upright at Y≈0")
    assert table_min<field_min-450 and below>200, (
        "legs must be physically BELOW the field; check model axes/importer")
    assert table_max>field_max+70, (
        "side rim must stand ABOVE the pitch, not underneath it")
    print("PASS: 3D CC BY foosball has real legs UNDER the playing field")


if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("asset_folder",type=Path,nargs="?",default=Path("local_assets/3d"))
    verify(p.parse_args().asset_folder)
